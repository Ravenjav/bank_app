-- 1. Структура

CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    amount DECIMAL(15, 2) NOT NULL,
    risk_score INTEGER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT fk_applications_client
        FOREIGN KEY (client_id)
    REFERENCES clients(id),

    CONSTRAINT chk_applications_amount
        CHECK (amount > 0),

    CONSTRAINT chk_applications_score
        CHECK (risk_score IS NULL OR risk_score IN (10, 50, 100))
);

CREATE INDEX idx_applications_client_id
    ON applications(client_id);

